import { evalExpr, exprError, isExpression, exprNames, renameInExpr, resolveVars } from '../src/util.js';
let fails = 0;
const eq = (name, got, want) => { const ok = typeof want === 'number' ? Math.abs(got - want) < 1e-9 || (Number.isNaN(want) && Number.isNaN(got)) : got === want; if (!ok) fails++; console.log(ok ? 'ok  ' : 'FAIL', name, '→', got, ok ? '' : '(want ' + want + ')'); };
eq('25.4*2', evalExpr('25.4*2'), 50.8);
eq('3/8in', evalExpr('3/8in'), 9.525);
eq('2cm + units', evalExpr('2cm'), 20);
eq('precedence 2+3*4^2', evalExpr('2+3*4^2'), 50);
eq('right-assoc 2^3^2', evalExpr('2^3^2'), 512);
eq('unary -(2+3)*-2', evalExpr('-(2+3)*-2'), 10);
eq('sin(30) degrees', evalExpr('sin(30)'), 0.5);
eq('max(3, wall*2)', evalExpr('max(3, wall*2)', { wall: 2 }), 4);
eq('pi*2', evalExpr('pi*2'), Math.PI * 2);
eq('1e3', evalExpr('1e3'), 1000);
eq('variable pin (not "in" unit)', evalExpr('pin+1', { pin: 4 }), 5);
eq('unknown name → NaN', evalExpr('foo+1'), NaN);
eq('no code injection', evalExpr('alert(1)'), NaN);
eq('garbage', evalExpr('2+*3'), NaN);
eq('error message', exprError('bolt*2', {}), 'Unknown name "bolt"');
eq('isExpression("10+5")', isExpression('10+5'), false);
eq('isExpression("3in")', isExpression('3in'), false);
eq('isExpression("wall*2")', isExpression('wall*2'), true);
eq('exprNames', exprNames('max(wall, h)*2+pi').join(','), 'wall,h');
eq('renameInExpr', renameInExpr('wall*2 + wall2 + max(wall, 1)', 'wall', 'w'), 'w*2 + wall2 + max(w, 1)');
const r = resolveVars([{ name: 'b', expr: 'a*2' }, { name: 'a', expr: '5' }, { name: 'c', expr: 'd' }, { name: 'd', expr: 'c' }, { name: 'x', expr: 'nope' }]);
eq('vars resolve out of order', r.values.b, 10);
eq('circular detected', r.errors.c, 'Circular reference');
eq('unknown detected', r.errors.x, 'Unknown name "nope"');
process.exit(fails ? 1 : 0);
