// Generates src/fonts/catalog.js from the installed @fontsource packages (regular + bold, Latin).
// Run with: node scripts/gen-fonts.mjs
import { readdirSync, writeFileSync, existsSync } from 'node:fs';

const FAMILIES = [
	// [package, label, category]
	['roboto', 'Roboto', 'Sans'], ['open-sans', 'Open Sans', 'Sans'], ['montserrat', 'Montserrat', 'Sans'], ['lato', 'Lato', 'Sans'],
	['poppins', 'Poppins', 'Sans'], ['inter', 'Inter', 'Sans'], ['nunito', 'Nunito', 'Sans'], ['raleway', 'Raleway', 'Sans'],
	['rubik', 'Rubik', 'Sans'], ['oswald', 'Oswald', 'Sans'], ['exo-2', 'Exo 2', 'Sans'], ['comfortaa', 'Comfortaa', 'Sans'],
	['fredoka', 'Fredoka', 'Sans'], ['baloo-2', 'Baloo 2', 'Sans'], ['archivo-black', 'Archivo Black', 'Sans'], ['anton', 'Anton', 'Sans'],
	['bebas-neue', 'Bebas Neue', 'Sans'], ['russo-one', 'Russo One', 'Sans'],
	['merriweather', 'Merriweather', 'Serif'], ['playfair-display', 'Playfair Display', 'Serif'], ['roboto-slab', 'Roboto Slab', 'Serif'],
	['lora', 'Lora', 'Serif'], ['bitter', 'Bitter', 'Serif'], ['cinzel', 'Cinzel', 'Serif'], ['abril-fatface', 'Abril Fatface', 'Serif'],
	['alfa-slab-one', 'Alfa Slab One', 'Serif'],
	['roboto-mono', 'Roboto Mono', 'Mono'], ['space-mono', 'Space Mono', 'Mono'], ['courier-prime', 'Courier Prime', 'Mono'],
	['press-start-2p', 'Press Start 2P', 'Mono'],
	['orbitron', 'Orbitron', 'Display'], ['audiowide', 'Audiowide', 'Display'], ['righteous', 'Righteous', 'Display'],
	['bungee', 'Bungee', 'Display'], ['bangers', 'Bangers', 'Display'], ['luckiest-guy', 'Luckiest Guy', 'Display'],
	['titan-one', 'Titan One', 'Display'], ['black-ops-one', 'Black Ops One', 'Display'], ['creepster', 'Creepster', 'Display'],
	['special-elite', 'Special Elite', 'Display'], ['unifrakturmaguntia', 'UnifrakturMaguntia', 'Display'],
	['saira-stencil-one', 'Saira Stencil One', 'Stencil'], ['allerta-stencil', 'Allerta Stencil', 'Stencil'], ['stardos-stencil', 'Stardos Stencil', 'Stencil'],
	['lobster', 'Lobster', 'Script'], ['pacifico', 'Pacifico', 'Script'], ['dancing-script', 'Dancing Script', 'Script'],
	['great-vibes', 'Great Vibes', 'Script'], ['caveat', 'Caveat', 'Script'], ['satisfy', 'Satisfy', 'Script'],
	['kaushan-script', 'Kaushan Script', 'Script'], ['permanent-marker', 'Permanent Marker', 'Script'],
];

const imports = [], entries = [];
let k = 0;
for (const [pkg, label, cat] of FAMILIES) {
	const dir = `node_modules/@fontsource/${pkg}/files`;
	if (!existsSync(dir)) { console.warn('missing', pkg); continue; }
	const weights = readdirSync(dir).map((f) => new RegExp(`^${pkg}-latin-(\\d+)-normal\\.woff$`).exec(f)).filter(Boolean).map((m) => +m[1]).sort((a, b) => a - b);
	if (!weights.length) { console.warn('no latin woff', pkg); continue; }
	const regular = weights.includes(400) ? 400 : weights[0];
	const boldW = weights.includes(700) ? 700 : weights.filter((w) => w > regular).pop();
	const faces = {};
	for (const [style, w] of [['regular', regular], ['bold', boldW]]) {
		if (!w) continue;
		const v = 'f' + k++;
		imports.push(`import ${v} from '@fontsource/${pkg}/files/${pkg}-latin-${w}-normal.woff';`);
		faces[style] = v;
	}
	entries.push(`\t{ id: '${pkg}', label: '${label}', cat: '${cat}', faces: { ${Object.entries(faces).map(([s, v]) => `${s}: ${v}`).join(', ')} } },`);
}
writeFileSync('src/fonts/catalog.js', `// Generated by scripts/gen-fonts.mjs — Latin subsets of open-source fonts from Fontsource (SIL OFL / Apache).
// Each face is a base64 WOFF string, decoded and parsed only when first used.
${imports.join('\n')}

export const CATALOG = [
${entries.join('\n')}
];
`);
console.log(`${entries.length} families, ${imports.length} faces`);
